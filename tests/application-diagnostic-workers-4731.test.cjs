const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { once } = require('node:events');
const { Worker } = require('node:worker_threads');
const { createApplicationLogSession } = require('../electron/lib/application-log-session.cjs');
const { createToolObserver } = require('../electron/lib/application-log-tools.cjs');
const { installWorkerObservation } = require('../electron/lib/application-log-workers.cjs');

test('real app-owned Node workers keep original stdout forwarding, messages and errors while explicit capture exports code text once', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'veylo-worker-diagnostics-'));
  await fs.mkdir(path.join(root, 'electron/lib'), { recursive: true });
  const workerFile = path.join(root, 'electron/lib/synthetic-worker.cjs');
  await fs.writeFile(workerFile, "const {parentPort}=require('node:worker_threads');console.log('WORKER_STDOUT_MARKER password=WORKER_FIXTURE_SECRET');console.error('WORKER_STDERR_MARKER');parentPort.postMessage({same:'original message'});");
  let observer;
  const session = createApplicationLogSession({ directory: path.join(root, 'logs'), metadata: { version: '4.7.31' }, onBeforeStop: () => observer.flush(), onRecordingChanged: () => observer.reset() });
  observer = createToolObserver({ record: row => session.record(row), isEnabled: session.isRecording, noteLoss: session.noteLoss });
  const threads = { Worker }, remove = installWorkerObservation({ workerThreads: threads, appRoot: root, observeToolProcess: observer.observe });
  t.after(async () => { remove(); observer.cleanup(); await session.dispose(); await fs.rm(root, { recursive: true, force: true }); });
  await session.start();
  const worker = new threads.Worker(workerFile, { workerData: { body: 'PRIVATE_WORKER_DATA' } });
  assert.equal(worker instanceof Worker, true); assert.equal(worker.constructor, Worker);
  const received = once(worker, 'message'), exit = once(worker, 'exit');
  assert.deepEqual((await received)[0], { same: 'original message' }); assert.equal((await exit)[0], 0);
  const unknown = new threads.Worker("console.log('UNKNOWN_PRIVATE_OUTPUT')", { eval: true }); await once(unknown, 'exit');
  const privateOutput = new threads.Worker(workerFile, { stdout: true, stderr: true });
  let owned = ''; privateOutput.stdout.on('data', bytes => { owned += bytes.toString(); }); privateOutput.stderr.resume();
  await once(privateOutput, 'exit'); assert.ok(owned.includes('WORKER_STDOUT_MARKER'));
  const failureFile = path.join(root, 'electron/lib/failure-worker.cjs');
  await fs.writeFile(failureFile, "throw new Error('WORKER_FAILURE_MARKER password=WORKER_FAILURE_SECRET');");
  const failure = new threads.Worker(failureFile), failed = new Promise(resolve => failure.once('exit', resolve));
  let originalError; failure.once('error', error => { originalError = error; });
  assert.equal(failure.listenerCount('error'), 1, 'Observation uses errorMonitor, not an error consumer');
  assert.equal(await failed, 1); assert.ok(originalError.message.includes('WORKER_FAILURE_MARKER'));
  await session.stop();
  const text = await session.text(), rows = text.trim().split('\n').map(JSON.parse);
  assert.equal(rows.filter(row => row.message?.includes('WORKER_STDOUT_MARKER')).length, 1);
  assert.ok(text.includes('WORKER_STDERR_MARKER'));
  assert.ok(text.includes('WORKER_FAILURE_MARKER')); assert.match(text, /electron\/lib\/failure-worker\.cjs:\d+:\d+/);
  assert.doesNotMatch(text, /WORKER_FIXTURE_SECRET|WORKER_FAILURE_SECRET|PRIVATE_WORKER_DATA|UNKNOWN_PRIVATE_OUTPUT/);
  assert.ok(rows.some(row => row.tool === 'worker' && row.event === 'exit' && row.exitCode === 0));
  remove(); assert.equal(threads.Worker, Worker);
});
